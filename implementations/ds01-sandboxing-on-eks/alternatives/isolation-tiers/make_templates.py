"""Builds the Kata, gVisor and gVisor-with-GPU variants of the python template from the real one in k8s/20-sandboxes.yaml.

Run from this folder:  python3 make_templates.py
It writes sandbox-templates.yaml, or the path given as the first argument. check.sh re-runs it and fails if the committed file has drifted from the original, so the
variants cannot silently disagree with the template they were derived from.
Only three things differ from python-untrusted: the name, the runtime class, and (for the GPU variant) one GPU in the limits.
Everything that makes the sandbox a sandbox (no service account token, read-only root, dropped capabilities, the one egress rule,
the gateway CA) is copied as it is.
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / "k8s" / "20-sandboxes.yaml"
RUNTIME_LINE = "      runtimeClassName: isolated-sandbox      # Tier 2: one microVM per pod\n"
LIMITS_LINE = '            limits: { cpu: "1", memory: 1Gi }\n'

docs = SOURCE.read_text().split("\n---\n")
original = next(d for d in docs if "kind: SandboxTemplate" in d and "name: python-untrusted\n" in d)
for needed in (RUNTIME_LINE, LIMITS_LINE):
    if needed not in original:
        sys.exit(f"the original template no longer contains {needed.strip()!r}; update this script")
# The leading comment of the original describes the original, so it is dropped from the variants.
original = original[original.index("apiVersion:"):]

VARIANTS = [
    # name, runtime class, tier label, comment, extra limit
    ("python-kata", "kata-qemu-runtime-rs", "kata", "Kata Containers microVM on a nested-virtualization node (self-managed Karpenter).", False),
    ("python-gvisor", "gvisor", "gvisor", "gVisor user-space kernel on an ordinary node.", False),
    ("python-gpu", "gvisor-gpu", "gvisor-gpu", "gVisor with nvproxy, one GPU per sandbox.", True),
]
out = ["# Generated by make_templates.py from python-untrusted in k8s/20-sandboxes.yaml. Do not edit by hand."]
for name, runtime, label, comment, gpu in VARIANTS:
    t = original.replace("name: python-untrusted\n", f"name: {name}\n", 1)
    t = t.replace(RUNTIME_LINE, f"      runtimeClassName: {runtime}      # {comment}\n", 1)
    t = t.replace('ds01/tier: "2"', f'ds01/tier: "2"\n        ds01/runtime: {label}', 1)
    if gpu:
        t = t.replace(LIMITS_LINE, '            limits: { cpu: "1", memory: 1Gi, nvidia.com/gpu: "1" }\n', 1)
    pool = (
        "apiVersion: extensions.agents.x-k8s.io/v1beta1\nkind: SandboxWarmPool\nmetadata:\n"
        f"  name: {name}-pool\n  namespace: sandboxes\nspec:\n  replicas: ${{{name.replace('-', '_')}_pool_replicas}}\n"
        f"  sandboxTemplateRef:\n    name: {name}\n"
    )
    out.append("---\n# " + comment + "\n" + t.rstrip("\n") + "\n---\n" + pool.rstrip("\n"))
target = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "sandbox-templates.yaml"
target.write_text("\n".join(out) + "\n")
print("wrote", target)
