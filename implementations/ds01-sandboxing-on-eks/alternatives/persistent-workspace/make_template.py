"""Builds the persistent variant of the python template from the real one in k8s/20-sandboxes.yaml.

Run from this folder:  python3 make_template.py > sandbox-template-persistent.yaml
check.sh re-runs it and fails if the committed file has drifted from the template it was derived from, so the two cannot
silently disagree. The ${...} placeholders are left as they are; terraform fills them the same way it does for the original.
"""
import pathlib
import re
import sys

SOURCE = pathlib.Path(__file__).resolve().parents[2] / "k8s" / "20-sandboxes.yaml"
docs = SOURCE.read_text().split("\n---\n")
template = next(d for d in docs if "kind: SandboxTemplate" in d and "name: python-untrusted\n" in d)

out = template.replace("name: python-untrusted\n", "name: python-persistent\n", 1)
out = out.replace('ds01/tier: "2"', 'ds01/tier: "2"\n        ds01/persistent: "true"', 1)
# The workspace is no longer a scratch directory. The controller adds the volume from volumeClaimTemplates below.
scratch = "        - { name: workspace, emptyDir: { sizeLimit: 2Gi } }\n"
if scratch not in out:
    sys.exit("the original template no longer has the workspace emptyDir line this script replaces")
out = out.replace(scratch, "", 1)
out = out.rstrip("\n") + """
  volumeClaimTemplates:
    - metadata:
        name: workspace                 # the PVC is named workspace-<sandbox name>
      spec:
        accessModes: ["ReadWriteOncePod"]   # one pod at a time; the only mode EKS Auto Mode supports for EBS in a sandbox
        storageClassName: auto-ebs-sc
        resources:
          requests: { storage: 2Gi }
"""
pool = """apiVersion: extensions.agents.x-k8s.io/v1beta1
kind: SandboxWarmPool
metadata:
  name: python-persistent-pool
  namespace: sandboxes
spec:
  replicas: ${persistent_pool_replicas}
  sandboxTemplateRef:
    name: python-persistent
"""
print("# Generated by make_template.py from python-untrusted in k8s/20-sandboxes.yaml. Do not edit by hand.")
print(out.rstrip("\n"))
print("---")
print(pool.rstrip("\n"))
